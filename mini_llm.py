from sentence_transformers import SentenceTransformer
import faiss
import numpy as np

# embedding model
embedder = SentenceTransformer("all-MiniLM-L6-v2")

# convert text → vectors
doc_embeddings = embedder.encode([c["text"] for c in chunks])

# FAISS index
dim = doc_embeddings.shape[1]
index = faiss.IndexFlatL2(dim)
index.add(np.array(doc_embeddings))

def retrieve(query, k=2):
    q_emb = embedder.encode([query])

    distances, indices = index.search(q_emb, k)

    return [chunks[i] for i in indices[0]]

def generate_with_rag(query):

    #  retrieve relevant context
    context_chunks = retrieve(query, k=2)

    context_text = " ".join([c["text"] for c in context_chunks])

    # build prompt
    prompt = context_text + " " + query

    #  limit length (important for your small model)
    prompt_words = prompt.split()[-20:]   # keep last tokens
    prompt = " ".join(prompt_words)

    #  generate using model
    return generate(prompt)

def generate(seed, steps=200, temperature=0.3):
    ids = tokenizer.encode(seed).ids

    for _ in range(steps):
        seq = ids[-seq_len:]

        if len(seq) < seq_len:
            seq = [0] * (seq_len - len(seq)) + seq

        seq = np.array(seq).reshape(1, seq_len)

        pred = model.predict(seq, verbose=0)
        probs = pred[0, -1]

        probs = np.log(probs + 1e-9) / temperature
        probs = np.exp(probs)
        probs = probs / np.sum(probs)

        next_id = np.random.choice(len(probs), p=probs)
        ids.append(next_id)

    return tokenizer.decode(ids)

