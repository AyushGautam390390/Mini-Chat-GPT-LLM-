@tf.keras.utils.register_keras_serializable()
class PositionalEmbedding(tf.keras.layers.Layer):
    def __init__(self, vocab_size, embed_dim, max_len):
        super().__init__()
        self.token_emb = Embedding(vocab_size, embed_dim)
        self.pos_emb   = Embedding(max_len, embed_dim)

    def call(self, x):
        positions = tf.range(tf.shape(x)[1])
        return self.token_emb(x) + self.pos_emb(positions)

class GPTBlock(tf.keras.layers.Layer):
    def __init__(self, embed_dim, heads, ff_dim):
        super().__init__()
        self.att  = MultiHeadAttention(num_heads=heads, key_dim=embed_dim)
        self.ffn  = tf.keras.Sequential([Dense(ff_dim, activation="relu"), Dense(embed_dim)])
        self.norm1 = LayerNormalization()
        self.norm2 = LayerNormalization()

    def call(self, x):
        attn = self.att(x, x, use_causal_mask=True)
        x = self.norm1(x + attn)
        return self.norm2(x + self.ffn(x))

# --------------------------
# GPT Model
# --------------------------

inputs = tf.keras.Input(shape=(seq_len,))

x = PositionalEmbedding(vocab_size, embed_dim, max_len)(inputs)

x = GPTBlock(embed_dim, heads, ff_dim)(x)
x = GPTBlock(embed_dim, heads, ff_dim)(x)

